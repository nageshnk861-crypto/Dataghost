"""
DataGhost – AI Explanation Routes (Ollama integration).

POST /api/ai/explain
    Accepts an incident / scan event context and returns a natural-language
    security explanation generated by a local Ollama model.

POST /api/ai/status
    Returns whether Ollama is reachable and which model is available.

The underlying security DECISION is always deterministic (risk engine + DLP
rules).  Ollama is used ONLY for human-readable explanations, so the system
remains safe even when Ollama is offline (graceful fallback text is returned).

Environment variables:
    OLLAMA_URL   – Ollama base URL (default: http://localhost:11434)
    OLLAMA_MODEL – Model tag to use  (default: gemma2:2b)
"""

from __future__ import annotations

import json
import logging
import os
from typing import Any, Dict, List, Optional

import httpx
from fastapi import APIRouter, Depends
from pydantic import BaseModel

from auth import get_current_user
from models import User

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/ai", tags=["AI"])

# ── Config ────────────────────────────────────────────────────────────────────
OLLAMA_URL: str = os.environ.get("OLLAMA_URL", "http://localhost:11434").rstrip("/")
OLLAMA_MODEL: str = os.environ.get("OLLAMA_MODEL", "gemma2:2b")
_REQUEST_TIMEOUT = 60  # seconds – generous for first token on cold model


# ── Schemas ───────────────────────────────────────────────────────────────────

class FindingSummary(BaseModel):
    category: str
    severity: str
    count: int = 1
    description: Optional[str] = None


class ExplainRequest(BaseModel):
    """All fields are optional so the caller can pass whatever it has."""
    incident_id:    Optional[str]            = None
    filename:       Optional[str]            = None
    classification: Optional[str]            = None
    risk_score:     Optional[int]            = None
    severity:       Optional[str]            = None
    action_taken:   Optional[str]            = None
    destination:    Optional[str]            = None
    user:           Optional[str]            = None
    findings:       Optional[List[FindingSummary]] = None
    extra_context:  Optional[str]            = None   # raw JSON / free text


class ExplainResponse(BaseModel):
    explanation:  str
    model:        str
    ollama_used:  bool
    available:    bool


class StatusResponse(BaseModel):
    available:    bool
    url:          str
    model:        str
    models:       List[str]
    message:      str


# ── Prompt builder ────────────────────────────────────────────────────────────

def _build_prompt(req: ExplainRequest) -> str:
    """
    Build a focused, security-analyst-style prompt from the event context.
    The prompt is deterministic; Ollama provides only the explanation text.
    """
    findings_text = ""
    if req.findings:
        lines = []
        for f in req.findings:
            desc = f" ({f.description})" if f.description else ""
            lines.append(f"  • {f.category} [{f.severity}]{desc} — {f.count} match(es)")
        findings_text = "\n".join(lines)
    else:
        findings_text = "  • (no detailed findings provided)"

    risk_label = req.risk_score or "N/A"
    severity   = req.severity or "UNKNOWN"
    action     = req.action_taken or "LOGGED"
    dest       = req.destination or "Unknown"
    user       = req.user or "Unknown"
    fname      = req.filename or "Unknown file"
    classif    = req.classification or "UNCLASSIFIED"

    return f"""You are DataGhost, an AI-powered Data Loss Prevention security analyst.
A security event has been detected. Explain this event in plain English in exactly 3–4 sentences.
Structure your explanation as:
1. What sensitive data was detected and why it is risky.
2. Why the destination or action made this suspicious.
3. What action was taken and what the user/admin should do next.

Keep the tone professional, factual, and concise. Do NOT repeat the raw numbers as a list.

── EVENT DETAILS ──────────────────────────────────────────
File         : {fname}
User         : {user}
Destination  : {dest}
Classification: {classif}
Risk Score   : {risk_label}/100
Severity     : {severity}
Action Taken : {action}

Detected findings:
{findings_text}
──────────────────────────────────────────────────────────

Explanation:"""


# ── Ollama helpers ────────────────────────────────────────────────────────────

async def _check_ollama() -> Dict[str, Any]:
    """
    Ping Ollama and return { available, models }.
    Uses a short timeout so callers don't hang if Ollama is not running.
    """
    try:
        async with httpx.AsyncClient(timeout=4.0) as client:
            r = await client.get(f"{OLLAMA_URL}/api/tags")
            if r.status_code == 200:
                data = r.json()
                models = [m["name"] for m in data.get("models", [])]
                return {"available": True, "models": models}
    except Exception:
        pass
    return {"available": False, "models": []}


async def _generate(prompt: str) -> Optional[str]:
    """
    Call Ollama /api/generate (non-streaming).
    Returns the response text, or None on any error.
    """
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.3,   # lower = more factual
            "num_predict": 300,   # ~3–4 sentences
        },
    }
    try:
        async with httpx.AsyncClient(timeout=_REQUEST_TIMEOUT) as client:
            r = await client.post(f"{OLLAMA_URL}/api/generate", json=payload)
            if r.status_code == 200:
                return r.json().get("response", "").strip()
    except Exception as exc:
        logger.warning("Ollama generate error: %s", exc)
    return None


# ── Fallback text ─────────────────────────────────────────────────────────────

def _fallback_explanation(req: ExplainRequest) -> str:
    """
    Rule-based explanation used when Ollama is unavailable.
    Deterministic and always safe to return.
    """
    fname    = req.filename or "the file"
    classif  = req.classification or "sensitive"
    severity = req.severity or "HIGH"
    action   = req.action_taken or "logged"
    dest     = req.destination or "an external destination"
    score    = req.risk_score or 0

    # Summarise detected types
    types: List[str] = []
    if req.findings:
        seen = set()
        for f in req.findings:
            cat = f.category.replace("_", " ").title()
            if cat not in seen:
                types.append(cat)
                seen.add(cat)
    type_text = (
        ", ".join(types[:4]) + (" and more" if len(types) > 4 else "")
        if types else "sensitive information"
    )

    action_msg = (
        "The transfer was blocked to prevent data exfiltration."
        if "BLOCK" in action.upper()
        else "The event was logged and flagged for review."
    )

    return (
        f"DataGhost detected {type_text} in {fname}, classifying it as {classif} "
        f"with a risk score of {score}/100 ({severity} severity). "
        f"The combination of sensitive data content and the transfer destination "
        f"({dest}) triggered DataGhost's risk engine. "
        f"{action_msg} "
        f"A security analyst should review this incident and verify whether the "
        f"transfer was authorised."
    )


# ── Endpoints ─────────────────────────────────────────────────────────────────

@router.post("/explain", response_model=ExplainResponse)
async def explain_event(
    req: ExplainRequest,
    current_user: User = Depends(get_current_user),
) -> ExplainResponse:
    """
    Generate a plain-English security explanation for a DataGhost event.

    Tries Ollama first; falls back to a deterministic rule-based explanation
    if Ollama is not running or returns an error.  The security DECISION is
    never affected by this endpoint.
    """
    status = await _check_ollama()
    ollama_text: Optional[str] = None

    if status["available"]:
        prompt = _build_prompt(req)
        ollama_text = await _generate(prompt)
        if ollama_text:
            logger.info(
                "AI explain: Ollama (%s) used for incident=%s",
                OLLAMA_MODEL, req.incident_id or "ad-hoc",
            )

    if ollama_text:
        return ExplainResponse(
            explanation=ollama_text,
            model=OLLAMA_MODEL,
            ollama_used=True,
            available=True,
        )

    # Fallback
    logger.info("AI explain: Ollama unavailable, using rule-based fallback")
    return ExplainResponse(
        explanation=_fallback_explanation(req),
        model="rule-based",
        ollama_used=False,
        available=status["available"],
    )


@router.get("/status", response_model=StatusResponse)
async def ai_status(
    current_user: User = Depends(get_current_user),
) -> StatusResponse:
    """Return whether Ollama is reachable and which models are loaded."""
    status = await _check_ollama()
    if status["available"]:
        models = status["models"]
        has_model = any(OLLAMA_MODEL in m for m in models)
        message = (
            f"Ollama is running. Model '{OLLAMA_MODEL}' is {'loaded' if has_model else 'not loaded — run: ollama pull ' + OLLAMA_MODEL}."
        )
    else:
        models = []
        message = (
            f"Ollama is not reachable at {OLLAMA_URL}. "
            f"Install from https://ollama.com and run: ollama pull {OLLAMA_MODEL}"
        )
    return StatusResponse(
        available=status["available"],
        url=OLLAMA_URL,
        model=OLLAMA_MODEL,
        models=models,
        message=message,
    )
